package main

import (
	"errors"
	"flag"
	"fmt"
	"log"
	"os"
	"regexp"
	"strings"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		log.Printf("ERROR: %v", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) == 0 {
		return errors.New("a command is required: schedule, backup, or restore")
	}
	command := args[0]
	flags := flag.NewFlagSet(command, flag.ContinueOnError)
	flags.SetOutput(os.Stdout)
	frequency := flags.String("frequency", "", "Backup frequency label (default: BACKUP_FREQUENCY or daily)")
	var timestamp string
	var backupName string
	var latest bool
	var databases stringList
	if command == "restore" {
		flags.StringVar(&timestamp, "timestamp", "", "UTC backup timestamp in YYYYMMDDTHHMMSSZ format")
		flags.StringVar(&backupName, "backup-name", "", "Backup dump filename generated by backup-sys")
		flags.BoolVar(&latest, "latest", false, "Restore the newest complete backup set for the selected databases")
		flags.Var(&databases, "database", "Configured database alias to restore; repeat to select multiple")
	} else if command != "backup" && command != "schedule" {
		return fmt.Errorf("unknown command %q; expected schedule, backup, or restore", command)
	}
	if err := flags.Parse(args[1:]); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return nil
		}
		return err
	}
	if flags.NArg() != 0 {
		return fmt.Errorf("unexpected arguments: %s", strings.Join(flags.Args(), " "))
	}
	if *frequency == "" {
		*frequency = env("BACKUP_FREQUENCY", "daily")
	}
	settings, err := loadSettings()
	if err != nil {
		return err
	}
	if command == "backup" {
		created, err := createBackup(settings, *frequency)
		if err != nil {
			return err
		}
		log.Printf("Backup set completed: %s", created)
		return nil
	}
	if command == "restore" {
		selectors := 0
		if timestamp != "" {
			selectors++
		}
		if backupName != "" {
			selectors++
		}
		if latest {
			selectors++
		}
		if selectors != 1 {
			return errors.New("restore requires exactly one of --timestamp, --backup-name, or --latest")
		}
		return restoreBackup(settings, timestamp, backupName, *frequency, databases, latest)
	}
	return schedule(settings, *frequency)
}

type stringList []string

func (s *stringList) String() string { return strings.Join(*s, ",") }
func (s *stringList) Set(value string) error {
	*s = append(*s, value)
	return nil
}

